// Обратная связь офлайн-движка. ТЗ, блок 10: ровно три части,
// по-русски, только про этот разговор, без общих оценок.
//
// Каждое правило обязано ссылаться на то, что человек РЕАЛЬНО сказал —
// поэтому в шаблоны передаётся его собственная фраза. Ничего не выдумываем:
// если зацепиться не за что, честно говорим об этом, а не хвалим впустую.
//
// Это КОНТЕНТ: формулировки правятся без программиста.
// Тон по блоку 5 — понимающий коллега на равных, обращение на «ты».

const q = (s) => `«${s}»`;

// ---------- Что получилось. Берётся первое подходящее правило сверху. ----------
export const WINS = [
  {
    id: "asked-question",
    when: (s) => s.askedQuestion,
    text: (s) =>
      `Ты не только отвечал(а), но и сам(а) спросил(а): ${q(s.questionText)}. ` +
      `Из-за этого разговор не превратился в интервью в одну сторону.`,
  },
  {
    id: "clarified",
    when: (s) => s.clarified,
    text: (s) =>
      `Когда стало непонятно, ты не кивнул(а) молча, а переспросил(а): ${q(s.clarifyText)}. ` +
      `В живом разговоре это важнее идеальной грамматики.`,
  },
  {
    id: "elaborated",
    when: (s) => s.longestWords >= 8,
    text: (s) =>
      `Ты не отделался(ась) одним словом — например, сказал(а): ${q(s.longestText)}. ` +
      `Такой ответ даёт собеседнику, за что зацепиться.`,
  },
  {
    id: "closed",
    when: (s) => s.closed,
    text: (s) =>
      `Ты нормально свернул(а) разговор — ${q(s.closeText)}, а не оборвал(а) на полуслове. ` +
      `Попрощаться тоже нужно уметь.`,
  },
  {
    id: "introduced",
    when: (s) => s.introduced,
    text: (s) =>
      `Ты сам(а) рассказал(а) о себе, без вытягивания: ${q(s.introText)}. ` +
      `С этого начинается любое знакомство на конференции.`,
  },
  {
    id: "spoke",
    when: () => true,
    text: (s) =>
      `Ты заговорил(а) вслух по-английски с незнакомым человеком — ${s.turns} ` +
      `${s.turns === 1 ? "реплика" : s.turns < 5 ? "реплики" : "реплик"}. ` +
      `Это и есть самое трудное место, и ты его прошёл(ла).`,
  },
];

